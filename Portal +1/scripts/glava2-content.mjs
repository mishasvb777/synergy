function p(text, opts = {}) {
  return new Paragraph({
    alignment: opts.align || AlignmentType.JUSTIFIED,
    spacing: { after: 120, line: 360 },
    indent: opts.indent === false ? {} : { firstLine: 709 },
    children: [
      new TextRun({
        text,
        font: 'Times New Roman',
        size: 28,
        bold: !!opts.bold,
      }),
    ],
  });
}

function title(text) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 200, after: 200, line: 360 },
    children: [new TextRun({ text, font: 'Times New Roman', size: 28, bold: true })],
  });
}

function h(text) {
  return new Paragraph({
    alignment: AlignmentType.LEFT,
    spacing: { before: 240, after: 120, line: 360 },
    children: [new TextRun({ text, font: 'Times New Roman', size: 28, bold: true })],
  });
}

function caption(text) {
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 80, after: 200, line: 360 },
    children: [new TextRun({ text, font: 'Times New Roman', size: 28, bold: true })],
  });
}

function pngSize(buf) {
  return { width: buf.readUInt32BE(16), height: buf.readUInt32BE(20) };
}

function img(file, maxW = 560) {
  if (!fs.existsSync(file)) {
    return p(`[нет файла: ${path.basename(file)}]`, { indent: false, align: AlignmentType.CENTER });
  }
  const buf = fs.readFileSync(file);
  const { width: iw, height: ih } = pngSize(buf);
  const width = maxW;
  const height = Math.max(180, Math.round((ih / iw) * maxW));
  return new Paragraph({
    alignment: AlignmentType.CENTER,
    spacing: { before: 120, after: 40 },
    children: [
      new ImageRun({
        type: 'png',
        data: buf,
        transformation: { width, height },
      }),
    ],
  });
}

function table(headers, rows) {
  const width = Math.floor(9000 / headers.length);
  const mk = (text, bold = false) =>
    new TableCell({
      borders: border,
      width: { size: width, type: WidthType.DXA },
      children: [
        new Paragraph({
          spacing: { after: 40, line: 276 },
          children: [new TextRun({ text, font: 'Times New Roman', size: 22, bold })],
        }),
      ],
    });
  return new Table({
    width: { size: 9000, type: WidthType.DXA },
    rows: [
      new TableRow({ children: headers.map((hdr) => mk(hdr, true)) }),
      ...rows.map((r) => new TableRow({ children: r.map((c) => mk(String(c))) })),
    ],
  });
}

function step(text) {
  return p(text);
}

function shot(file, captionText) {
  return [img(path.join(shots, file)), caption(captionText)];
}

